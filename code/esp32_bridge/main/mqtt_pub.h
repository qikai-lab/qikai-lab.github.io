/*
 * mqtt_pub.h - MQTT 发布模块
 * ===========================================================================
 * 设计取舍（面试会被问「断网了数据怎么办」）：
 *
 *   这里**故意选择「断线直接丢、只计数」**，没有做本地缓存补发。
 *   理由：环境监测是每 1 秒一条的时序数据，断网 10 分钟后把 600 条
 *   历史数据一股脑补发上去，服务端拿到的时间戳全是「到达时间」而不是
 *   「采集时间」，等于制造了 600 条错误时间的数据 —— 比丢了更糟。
 *
 *   真正要给数据补时间，正确做法是设备端带上**采集时刻**（SNTP 对时后
 *   的时间戳），服务端按这个字段入库。那是阶段 C 的事，现在不做。
 *
 *   所以现阶段：断线期间的数据丢弃，但把丢弃条数**明确统计并打印**，
 *   让人一眼知道「这段数据不完整」，而不是假装什么都没发生。
 * ===========================================================================
 */
#ifndef MQTT_PUB_H
#define MQTT_PUB_H

#include <stdbool.h>
#include <stdint.h>

/**
 * @brief 初始化并启动 MQTT 客户端（内部自带自动重连，不会阻塞）
 * @return 0 成功；负数 失败
 */
int mqtt_pub_start(void);

/** 当前是否已连上 broker */
bool mqtt_pub_is_connected(void);

/**
 * @brief 发布一帧环境数据
 * @param raw 24 字节原始帧（调用方保证已经过合法性校验）
 * @return >=0 成功（消息 id）；<0 未连接或入队失败
 *
 * 这个函数**不阻塞**：QoS1 的发布只是把消息放进客户端内部的 outbox，
 * 真正收发在 MQTT 自己的任务里做。所以可以在接收任务里直接调。
 */
int mqtt_pub_env(const uint8_t *raw);

/** 统计：累计成功发布条数 */
uint32_t mqtt_pub_ok_count(void);

/** 统计：累计因未连接而丢弃的条数 */
uint32_t mqtt_pub_dropped_count(void);

#endif /* MQTT_PUB_H */
