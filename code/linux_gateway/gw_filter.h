/*
 * gw_filter.h - 数据加工层：中值滤波 + 自适应基线（M4）
 * ---------------------------------------------------------------------------
 * 为什么需要这一层
 * ----------------
 * CC2530 的 gas 字段是 MQ-2 的 ADC 原始值，直接拿来判阈值有两个问题：
 *
 *   1) **单帧尖峰**。ADC 采样偶尔会撞上电源纹波，某一帧突然跳到 30（基线 22）。
 *      这类孤立尖峰占 1~2 帧，直接判阈值会误报。
 *      中值滤波专治这个：5 帧窗口里取中间那个数，孤立尖峰必被挤掉。
 *
 *   2) **绝对值不可比**。MQ-2 的输出受温度、湿度、器件老化、加热丝电压影响，
 *      同一个房间放两个月，洁净空气基线可能从 35 漂到 60。
 *      写死「gas > 600 报警」这种阈值，换块板子、过个夏天就失效。
 *      所以用**相对基线的倍数**判定：gas 涨到基线的 2.5 倍才算烟雾。
 *
 * 两个模块都只用整数运算，不引入浮点（CC2530 端和 Linux 端保持同一套风格，
 * 而且定点数不会有 21.1 存成 21.099999 这种问题）。
 * ---------------------------------------------------------------------------
 */
#ifndef GW_FILTER_H
#define GW_FILTER_H

#include <stdint.h>

/* 中值窗口：5 帧。偶数窗口的中值要取平均，会引入小数，所以用奇数。
 * 代价是告警延迟约 2 秒（窗口中心落后 2 帧），对烟雾告警完全可以接受。 */
#define GW_MED_WINDOW   5

typedef struct {
    uint16_t buf[GW_MED_WINDOW];
    uint8_t  n;         /* 已填充的个数（上电前几帧不满窗口） */
    uint8_t  idx;       /* 下一个写入位置 */
    uint16_t med;       /* 最近一次算出的中值 */
} gw_medfilt_t;

/** @brief 清空滤波器 */
void gw_medfilt_init(gw_medfilt_t *f);

/**
 * @brief 送入一个采样值，返回当前中值
 * @note  窗口没填满时返回已填数据的中间值（不是 0），
 *        否则上电头 4 秒的中值恒为 0，告警逻辑会以为空气很干净。
 */
uint16_t gw_medfilt_push(gw_medfilt_t *f, uint16_t v);

/** @brief 只读最近一次的中值 */
uint16_t gw_medfilt_value(const gw_medfilt_t *f);

/*------------------------------------------------------------------------------
 * 自适应基线
 *
 * 做法：慢速滑动平均（指数加权）。每帧朝当前值挪一点点，
 * 时间常数 tau 帧 = tau 秒（1 秒 1 帧）。
 *
 * tau = 600 表示大约 10 分钟跟上一个新水平。
 *   太小 → 真的烟雾持续 10 分钟会被当成"新常态"，告警自己消失
 *   太大 → 换环境（开窗、搬家）后要等很久才准确
 * 600 秒是折中。**告警期间会冻结基线**，从根上避免这个问题。
 *
 * 精度说明：base 存 ×100 的定点。如果直接用 base += (gas - base)/tau，
 * 差值小于 tau 时整数除法得 0，基线会永远卡死不动（经典死区）。
 * 所以额外用 acc 累积余数。
 *----------------------------------------------------------------------------*/

typedef struct {
    int32_t  base_x100;     /* 基线 ×100 */
    int32_t  acc;           /* 除法余数累积，防整数死区 */
    uint16_t tau;           /* 时间常数（帧数） */
    uint8_t  valid;         /* 0 = 还没初始化，第一帧直接取该值 */
} gw_baseline_t;

/** @brief 初始化，tau 建议 600（约 10 分钟） */
void gw_baseline_init(gw_baseline_t *b, uint16_t tau);

/**
 * @brief 用一帧采样更新基线
 * @param gas    当前采样（建议传中值滤波后的值，更稳）
 * @param freeze 非 0 表示冻结（告警期间传 1，否则告警会把基线自己拉高）
 */
void gw_baseline_update(gw_baseline_t *b, uint16_t gas, int freeze);

/** @brief 取基线原值（0~1023 量纲） */
uint16_t gw_baseline_value(const gw_baseline_t *b);

/** @brief 基线是否已建立（上电第一帧之后才为 1） */
int gw_baseline_valid(const gw_baseline_t *b);

#endif /* GW_FILTER_H */
